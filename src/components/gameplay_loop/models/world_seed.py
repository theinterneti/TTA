"""
World Seed — the structured data assembled during the Genesis Session.

A WorldSeed is not filled out as a form. It is built progressively through
conversation with the Genesis Agent and emitted when the session completes.

See: docs/design/genesis-session.md
Issues: #224 (schema), #259 (agent)
"""

from __future__ import annotations

import hashlib
import json
from enum import StrEnum
from uuid import uuid4

from pydantic import BaseModel, Field, model_validator

# ── Enumerations ──────────────────────────────────────────────────────────────


class WorldTone(StrEnum):
    """The emotional register of the world."""

    GETTING_BETTER = "getting_better"
    GETTING_WORSE = "getting_worse"
    HOLDING_ON = "holding_on"  # stasis — things neither improve nor decline
    CYCLICAL = "cyclical"  # rises and falls, no clear direction


class PowerSource(StrEnum):
    """What makes things happen in this world."""

    MAGIC = "magic"
    TECHNOLOGY = "technology"
    POLITICS = "politics"  # human organisation and will
    BELIEF = "belief"  # faith, narrative, collective meaning
    NATURE = "nature"  # the land, seasons, primal forces
    LINEAGE = "lineage"  # blood, ancestry, inherited power
    COMBINATION = "combination"  # multiple sources in tension


class PlayerPosition(StrEnum):
    """Where the player sits relative to the world's power structures."""

    INSIDER = "insider"  # part of the system, knows how it works
    OUTSIDER = "outsider"  # lives at the edges, views it from outside
    ASCENDING = "ascending"  # moving from outside toward inside
    DESCENDING = "descending"  # fell from inside, now at the edges
    OBSERVER = "observer"  # deliberately apart from the structures


class WorldScale(StrEnum):
    """The scope of the world the player inhabits."""

    VILLAGE = "village"  # a single community and its immediate surrounds
    CITY = "city"  # one city and its districts
    REGION = "region"  # a city plus its hinterland
    CONTINENT = "continent"  # multiple nations and landscapes
    WORLD = "world"  # the full planet
    COSMIC = "cosmic"  # multiple worlds, planes, or realities


class TechLevel(StrEnum):
    """The technology era of the world (absent magic considerations)."""

    STONE = "stone"
    BRONZE = "bronze"
    IRON = "iron"
    MEDIEVAL = "medieval"
    RENAISSANCE = "renaissance"
    INDUSTRIAL = "industrial"
    ELECTRIC = "electric"
    INFORMATION = "information"
    POST_SCARCITY = "post_scarcity"


class MagicPresence(StrEnum):
    """How common and visible magic is in the world."""

    NONE = "none"
    RUMOURED = "rumoured"  # people believe it exists but few have seen it
    RARE = "rare"  # exists but extraordinary
    COMMON = "common"  # part of everyday life
    PERVASIVE = "pervasive"  # the foundation of how the world works


class Motivation(StrEnum):
    """What drives the player's character."""

    CURIOSITY = "curiosity"
    BELONGING = "belonging"
    JUSTICE = "justice"
    SURVIVAL = "survival"
    DISCOVERY = "discovery"
    FREEDOM = "freedom"
    REDEMPTION = "redemption"
    POWER = "power"
    LOVE = "love"
    DUTY = "duty"
    REVENGE = "revenge"
    CREATION = "creation"


# ── Guide character ───────────────────────────────────────────────────────────


class GuideCharacter(BaseModel):
    """
    The in-world form the Genesis Agent takes at the end of Act 4.

    Generated from the WorldSeed — not chosen or hardcoded.
    The narrator discovers who it is; it does not decide.
    """

    name: str
    entity_type: str  # e.g. "archivist", "AI fragment", "hedge oracle", "contact"
    social_position: str  # e.g. "unofficial, edge-dweller", "minor functionary"
    relationship_to_player: (
        str  # e.g. "old friend", "creditor", "stranger who owes them"
    )
    speech_register: str  # e.g. "warm, direct", "clipped, ironic", "formal, precise"
    intro_line: str  # the first thing the guide says in-world


# ── The WorldSeed ─────────────────────────────────────────────────────────────


class WorldSeed(BaseModel):
    """
    The structured world definition assembled by the Genesis Session.

    Four fields are required (the minimum viable seed that triggers the scene
    break to Act 3). All other fields are optional — they are either established
    during the session or generated by the world generators.

    A seed with only the four required fields is valid and fully generatable.
    """

    # ── Required: minimum viable seed ──────────────────────────────────────
    tone: WorldTone
    power_source: PowerSource
    player_position: PlayerPosition
    one_specific_detail: str = Field(
        description="A concrete, particular thing that exists in this world. "
        "Any one thing — a place, an object, a custom, a creature, a rule."
    )

    # ── World shape (established in session or generated) ──────────────────
    scale: WorldScale | None = None
    geography_archetype: str | None = Field(
        default=None,
        description="e.g. 'island chain', 'vast steppe', 'underground city network'",
    )
    era_tech_level: TechLevel | None = None
    magic_presence: MagicPresence | None = None
    magic_source: str | None = Field(
        default=None,
        description="How magic works: 'innate talent', 'years of study', 'bargain with old powers'",
    )

    # ── Culture (generated from world shape if not established) ────────────
    culture_base: str | None = Field(
        default=None,
        description="Dominant social structure: 'mercantile republic', 'theocracy', 'tribal confederacy'",
    )
    culture_tone: str | None = Field(
        default=None,
        description="The feel of the culture: naming style, core values, relationship to outsiders",
    )
    cultural_tension: str | None = Field(
        default=None,
        description="The world's fundamental unresolved conflict",
    )

    # ── Player's character ─────────────────────────────────────────────────
    character_name: str | None = None
    character_background: str | None = Field(
        default=None,
        description="Where in this world they grew up, what their family was",
    )
    character_motivation: Motivation | None = None
    character_trait: str | None = Field(
        default=None,
        description="One thing they are known for — a skill, a reputation, a quality",
    )
    character_secret: str | None = Field(
        default=None,
        description="The unresolved question that gives the narrative somewhere to go",
    )

    # ── Guide character (generated in Act 4) ──────────────────────────────
    guide: GuideCharacter | None = None

    # ── Meta ───────────────────────────────────────────────────────────────
    seed_hash: str | None = Field(
        default=None,
        description="SHA-256 of the minimum viable fields, for reproducible generation",
    )
    session_id: str = Field(default_factory=lambda: str(uuid4()))
    completed: bool = False

    @model_validator(mode="after")
    def compute_seed_hash(self) -> WorldSeed:
        """Compute a deterministic hash of the minimum viable fields."""
        if self.seed_hash is None:
            hashable = json.dumps(
                {
                    "tone": self.tone,
                    "power_source": self.power_source,
                    "player_position": self.player_position,
                    "one_specific_detail": self.one_specific_detail,
                },
                sort_keys=True,
            )
            self.seed_hash = hashlib.sha256(hashable.encode()).hexdigest()[:16]
        return self

    def is_minimum_viable(self) -> bool:
        """True when the seed has enough to trigger the Act 3 scene break."""
        return all(
            [
                self.tone is not None,
                self.power_source is not None,
                self.player_position is not None,
                bool(self.one_specific_detail),
            ]
        )

    def missing_fields(self) -> list[str]:
        """Fields still needed before the minimum viable seed is complete."""
        missing = []
        if self.tone is None:
            missing.append("tone")
        if self.power_source is None:
            missing.append("power_source")
        if self.player_position is None:
            missing.append("player_position")
        if not self.one_specific_detail:
            missing.append("one_specific_detail")
        return missing

    def character_is_complete(self) -> bool:
        """True when enough character fields exist to write the character into the world."""
        return bool(self.character_name and self.character_motivation)
